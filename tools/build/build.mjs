/**
 * Assemble the deployable site — the only build step in this project.
 *
 * docs/ARCHITECTURE.md §1 chose no bundler and named the conditions to revisit;
 * both fired (47 modules, a 17-deep serial @import chain) and the same paragraph
 * says what to do: concatenate at *deploy* time, not in development. That
 * distinction is the design of this file — it runs against a throwaway output
 * directory and never touches `src/`.
 *
 * It also owns the copying that used to live in the workflow's shell, so "what
 * ships" has ONE definition rather than one per consumer.
 *
 * Usage:  node tools/build/build.mjs [outdir]            default _site
 *         node tools/build/build.mjs <outdir> --desktop  the Tauri frontend
 */

import { build } from "esbuild";
import {
  readFileSync, writeFileSync, mkdirSync, readdirSync,
  statSync, copyFileSync, cpSync, rmSync, existsSync,
} from "node:fs";
import { join, dirname, resolve, relative } from "node:path";
import { gzipSync, brotliCompressSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

/**
 * What the two builds share is the point: the desktop app runs the same bundle
 * the website serves. Only what a `tauri://` origin cannot use differs — no host
 * config, no crawler files, and no /app pretty URL, that scheme doing no
 * extension stripping. The alternative was `frontendDist: "../../"`, which put
 * ~30 MB of node_modules, docs and stale _site into the installer.
 */
const DESKTOP = process.argv.includes("--desktop");
const OUT = resolve(ROOT, process.argv.slice(2).find(a => !a.startsWith("--")) || "_site");

/**
 * Two gates on the app's EAGER JavaScript, because they answer different
 * questions. A budget rather than a report, because "small payload" with no
 * number decays quietly — every addition is individually reasonable and the
 * total is nobody's job.
 *
 * BASELINE (eager-size.json) stops silent creep. It fails on any INCREASE past
 * a small tolerance, so growth has to be deliberate: the fix is to re-record the
 * number, which puts it in the diff where a reviewer sees it. That is the same
 * shape as the sw.js SHELL list and build-icons.py --check — the value is on
 * disk and the check is that reality still matches it.
 *
 * CEILING stops a deliberate disaster the baseline would happily ratchet
 * towards — a new dependency, a lazy panel gone eager. It is deliberately
 * generous, and that is only safe BECAUSE the baseline exists: creep is the
 * baseline's job now, so the ceiling does not have to be tight to be useful.
 *
 * 45 KB gzip was the original single gate and it did its job — ~35 KB when it
 * landed, and growth consumed the headroom until it fired. What it could not
 * survive was having no headroom left and no defined response: a gate that
 * blocks every change equally has stopped distinguishing between them. So the
 * headroom is restored (~20% over today) and the ratchet is what makes that
 * safe.
 *
 * MEASURED IN BROTLI, because that is what Cloudflare Pages serves. The gate
 * counted gzip for its whole life and gzip is ~14% larger here, so the number
 * written above was never the delivered size it was defending.
 */
const EAGER_JS_CEILING = 48 * 1024;

/** How much the baseline may drift before it must be re-recorded. Small enough
 *  that a real addition trips it, loose enough that a minifier bump does not. */
const BASELINE_TOLERANCE = 0.02;

/** Kept in step with SITE_ORIGIN in src/core/config.js, which this cannot import. */
const SITE_ORIGIN = "https://realtimeclipboard.com";

const rel = f => relative(OUT, f).replace(/\\/g, "/");
const gz = buf => gzipSync(buf, { level: 9 }).length;
const br = buf => brotliCompressSync(buf).length;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

/* ------------------------------------------------------------- copy ----- */

for (const f of [
  // index.html is the marketing page: unreachable inside the shell, and it
  // carries the ad tags. Shipping it put the AdSense client ID in the installer.
  ...(DESKTOP ? [] : ["index.html"]),
  "app.html", "manifest.webmanifest", "sw.js",
  // Without this, Pages serves index.html with HTTP 200 for unmatched paths and
  // every typo becomes a soft 404. The desktop shell has no router.
  ...(DESKTOP ? [] : ["404.html"]),
  // Crawler-facing, and meaningless inside the desktop shell. The IndexNow key
  // file's NAME is the credential — it is verified by fetching it at the origin
  // root, so filename and top-level placement both matter. ads.txt is the same
  // shape of thing: AdSense refuses most demand for a site without one.
  ...(DESKTOP ? [] : [
    "robots.txt", "sitemap.xml", "README.md",
    "llms.txt", "d10e264a86258c1431df1f72efb3cf83.txt", "ads.txt",
  ]),
  // Read at runtime by src/ui/features/whatsNew.js. Generated by
  // tools/release/changelog.mjs and committed, so there is only copying to do.
  "changelog.json", "CHANGELOG.md",
  // Consumed by Cloudflare Pages at deploy time, then removed from the served
  // output. `_headers` carries the CSP, HSTS and the sw.js cache rule — which is
  // to say the whole reason this site is not on GitHub Pages any more.
  ...(DESKTOP ? [] : ["_headers", "_redirects"]),
]) {
  if (existsSync(join(ROOT, f))) copyFileSync(join(ROOT, f), join(OUT, f));
}

/* The assets/ split is load-bearing rather than tidy: assets/icons/ is precached
   by the service worker, while assets/social/ is a share card only crawlers
   fetch and has no business in an offline cache. Both copied verbatim. */
for (const d of DESKTOP ? ["assets"] : ["assets", "docs"]) {
  if (existsSync(join(ROOT, d))) cpSync(join(ROOT, d), join(OUT, d), { recursive: true });
}

/* Found by scanning rather than named one by one, because a forgotten per-page
   edit fails silently as a 404 rather than as a broken build.

   !! These publish one level up from where they sit on disk, which is why every
   link inside them is root-absolute: a relative one resolves against the wrong
   depth in exactly one of the two places. See src/pages/CLAUDE.md. !! */
const PAGES_DIR = join(ROOT, "src/pages");
for (const d of DESKTOP ? [] : readdirSync(PAGES_DIR)) {
  if (!statSync(join(PAGES_DIR, d)).isDirectory()) continue;
  if (!existsSync(join(PAGES_DIR, d, "index.html"))) continue;
  cpSync(join(PAGES_DIR, d), join(OUT, d), { recursive: true });
  console.log("  content page: " + d + "/");
}

// Vestigial since the move off GitHub Pages, kept because it costs nothing and
// this output tree is what a self-hoster puts there: Jekyll ignores files
// starting with _, which is every chunk esbuild emits.
writeFileSync(join(OUT, ".nojekyll"), "");

/* ------------------------------------------------------------ bundle ---- */

const common = {
  bundle: true,
  format: "esm",
  minify: true,
  // Shipped on purpose: fetched only when devtools is open, and the opposite of
  // obfuscating an app whose trust model is that you can read it.
  sourcemap: true,
  // NOT optional. Without it esbuild INLINES dynamic imports, silently undoing
  // every lazy load in the codebase and making the payload worse while appearing
  // to have worked.
  splitting: true,
  logLevel: "error",
};

// metafile: the chunk filenames esbuild emits are content hashes, so they change
// whenever their contents do and are worthless for "what grew". The metafile maps
// every chunk back to the SOURCE modules inside it, which are stable names.
/**
 * Resolve ui/features/adsense.js to its stub for the desktop shell.
 *
 * `adNetwork()` already never returns "adsense" there, so this changes no
 * behaviour — it changes what is ON DISK. Google forbids ads in software
 * applications, and an identifier that cannot ship cannot be switched on by a
 * later CSP edit. tools/check/desktop-check.mjs fails the build if one returns.
 */
const AD_ORIGINS = [
  "https://pagead2.googlesyndication.com", "https://partner.googleadservices.com",
  "https://tpc.googlesyndication.com", "https://adservice.google.com",
  "https://fundingchoicesmessages.google.com", "https://ep1.adtrafficquality.google",
  "https://ep2.adtrafficquality.google", "https://googleads.g.doubleclick.net",
  "https://td.doubleclick.net", "https://stats.g.doubleclick.net",
];

/**
 * Blank the AdSense IDs in the desktop copy of config.js.
 *
 * The desktop never reads them — `adNetwork()` answers "house" there — but a
 * publisher ID sitting in an installer is an identifier that shipped where the
 * programme policy says ads may not go. Blanking it costs nothing and makes
 * tools/check/desktop-check.mjs able to assert absence rather than disuse.
 */
/* Set by the plugin below and asserted after the build. A filter that stops
   matching does not fail — it silently does nothing, which is the worst failure
   mode available to something whose job is removing ad identifiers from a
   binary. */
let strippedAdIds = false;

const stripAdIds = {
  name: "strip-ad-ids",
  setup(b) {
    /* [\\/] rather than /, because esbuild hands a plugin a NATIVE path. This
       filter had a literal forward slash, so it matched nothing on Windows and
       every AdSense identifier in config.js went into the Windows installer
       while macOS and Linux built clean. Google forbids ads in software
       applications: that is a policy breach shipped by a path separator. */
    b.onLoad({ filter: /core[\\/]config\.js$/ }, (args) => ({
      contents: (strippedAdIds = true, readFileSync(args.path, "utf8"))
        .replace(/(ADSENSE_CLIENT:\s*)"[^"]*"/, '$1""')
        .replace(/("(?:LEADERBOARD|RAIL|APP)":?\s*)"[^"]*"/g, '$1""')
        // The script-URL builder is eager in config.js, so the host reached the
        // installer even with every ID blanked.
        .replace(/adsense:\s*\([^)]*\)\s*=>\s*`[^`]*`/, 'adsense: () => ""'),
      loader: "js",
    }));
  },
};

const stubAdsense = {
  name: "stub-adsense",
  setup(b) {
    b.onResolve({ filter: /adsense\.js$/ }, args =>
      args.path.endsWith("adsense.stub.js")
        ? null
        : { path: join(ROOT, "tools/build/adsense.stub.js") });
  },
};

const appBuild = await build({
  ...common, entryPoints: [join(ROOT, "src/main.js")], outdir: join(OUT, "src"), metafile: true,
  plugins: DESKTOP ? [stubAdsense, stripAdIds] : [],
});

/* The check that would have caught the Windows leak everywhere. site-check
   greps the OUTPUT and stays the backstop; this asserts the MECHANISM ran, so a
   filter that stops matching is loud on every platform rather than only where
   the strings happen to survive into a chunk. */
if (DESKTOP && !strippedAdIds) {
  die("the strip-ad-ids plugin never ran — its filter did not match "
    + "src/core/config.js, so every ad identifier is still in the bundle");
}
// Skipped whole for the shell: nothing there navigates to index.html, and
// tags.js is the crawlable pages' ad loader — bundling it put the AdSense
// client ID in the installer. Gated around the call rather than inside
// `entryPoints`, so the list stays a literal array — tests/unit/static-check.mjs
// reads it with a regex to know which modules a page is allowed to name.
if (!DESKTOP) {
  await build({
    ...common,
    // Every module an HTML page names in a <script src> must be an entry point: the
    // deploy ships bundles, so one reachable only from markup is invisible to the
    // bundler and 404s on the single page that needs it.
    entryPoints: ["redirect", "landing", "faq", "download", "copy", "tags"].map(n => join(ROOT, `src/landing/${n}.js`)),
    outdir: join(OUT, "src/landing"),
  });
}

for (const p of ["src/styles/main.css", "src/landing/landing.css"]) {
  await build({
    entryPoints: [join(ROOT, p)],
    outfile: join(OUT, p),
    bundle: true,
    minify: true,
    logLevel: "error",
  });
}

/**
 * Not bundled: the panel fetches them on first open, and a QR modal's CSS has no
 * business in the critical path. The directory IS the list — grepping call sites
 * for `lazyStyleHref("…")` made the set a fact about call sites rather than the
 * tree, so a sheet could be fetched over the wire AND bundled with nothing
 * saying so.
 */
cpSync(join(ROOT, "src/styles/lazy"), join(OUT, "src/styles/lazy"), { recursive: true });

/* ------------------------------------------------------ pretty URLs ----- */

/**
 * The app is served at `/app`. The FILE is still `app.html`; only the
 * references to it change, and only here.
 *
 * Cloudflare Pages serves it there on its own — every .html asset answers at
 * its extensionless path. `_redirects` must NOT restate that: a rewrite onto
 * `/app.html` loops against the canonical redirect coming back the other way.
 * The note at the top of `_redirects` has the outage it caused.
 *
 * !! Rewritten in the deploy and NEVER on disk. Three things depend on the
 * source tree continuing to say `app.html`, and two of them fail silently:
 *
 *   1. the `tauri://` scheme does no extension stripping, so every `./app` link
 *      would 404 in the desktop app with the web build perfectly green.
 *   2. `python -m http.server` does not strip extensions either, so rewriting
 *      the source breaks the no-build dev loop (docs/ARCHITECTURE.md §1).
 *   3. static-check.mjs §11 pins the sw.js SHELL to files that exist on disk,
 *      and `./app` is not one. The deploy's SHELL is generated below instead.
 *
 * Anchored on quotes so it can only match a URL, never the prose in README.md or
 * robots.txt, and on a closing `"`, `'` or `#` so `./app.html#KEY` — how
 * landing.js hands over a session — keeps its fragment. !!
 *
 * The bare `/` alternative is for src/pages/, whose links are root-absolute:
 * without it they ship pointing at `/app.html` while every other page says
 * `/app`, two URLs for one page.
 */
const PRETTY =
  /(["'])((?:\.{1,2}\/)*|\/|https:\/\/realtimeclipboard\.com\/)app\.html(?=[#"'])/g;

/* Skipped for the desktop shell — reason 1 above. */
let prettied = [];
if (!DESKTOP) {
  for (const f of walk(OUT)) {
    if (!/\.(html|js|webmanifest)$/.test(f)) continue;
    const before = readFileSync(f, "utf8");
    const after = before.replace(PRETTY, "$1$2app");
    if (after === before) continue;
    writeFileSync(f, after);
    prettied.push(rel(f));
  }
  // The landing page alone carries three, so zero matches means the pattern
  // broke rather than that there was nothing to do.
  if (!prettied.length) die("the /app rewrite matched nothing — the link format changed");
  console.log(`  pretty URLs: ${prettied.length} files now point at /app`);
}

/**
 * The app footer's site links, for the desktop shell.
 *
 * They are root-absolute, which is right on the website and a 404 inside
 * Tauri: that origin is `http://tauri.localhost` and this build ships no
 * content pages at all (reason 1 above). So they are rewritten to the public
 * site and forced to open outside the shell — following one in place would
 * navigate the webview off the app and end the session.
 */
if (DESKTOP) {
  const appHtml = join(OUT, "app.html");
  const before = readFileSync(appHtml, "utf8");
  const after = before.replace(
    /<footer class="appfoot">[\s\S]*?<\/footer>/,
    block => block.replace(
      /href="(\/[a-z/-]*)"/g,
      `href="${SITE_ORIGIN}$1" target="_blank" rel="noopener"`));
  if (after === before) die("the desktop footer rewrite matched nothing — app.html changed");
  writeFileSync(appHtml, after);
  console.log(`  desktop: app footer links now point at ${SITE_ORIGIN}`);
}

/**
 * The desktop copy of app.html declares no ad origin.
 *
 * Tauri injects its own CSP and browsers intersect the two, so these origins
 * were already unreachable — but a policy that NAMES a host it must never use
 * reads as an oversight to whoever edits it next, and the whole point of
 * docs/decisions/0001 is that this exclusion is deliberate. GA4's hosts stay:
 * analytics runs on every surface, only ads do not.
 */
if (DESKTOP) {
  const appHtml = join(OUT, "app.html");
  const before = readFileSync(appHtml, "utf8");
  const after = AD_ORIGINS.reduce((s, o) => s.split(`${o} `).join("").split(` ${o}`).join(""), before);
  if (after === before) die("the desktop CSP strip matched nothing — app.html's policy changed");
  writeFileSync(appHtml, after);
  console.log(`  desktop: ${AD_ORIGINS.length} ad origins removed from the app CSP`);
}

/* --------------------------------------------------- service worker ----- */

/**
 * Stamp VERSION, and rewrite SHELL to what this build produced.
 *
 * VERSION: a changed sw.js is what tells the browser an update exists, and
 * bumping it by hand is a step someone forgets — pinning every returning user to
 * a stale shell. SHELL: sw.js ships SOURCE paths, right for development and
 * wrong for the deploy, and `cache.addAll()` rejects as a unit, so one stale
 * entry kills the install and offline support with no visible symptom.
 *
 * !! Cloudflare Pages builds from a COMMIT, with `GITHUB_*` unset entirely. An
 * earlier version read GITHUB_REF_NAME alone and would have fallen through to
 * the literal "dev" on every production deploy — a stable cache name, so the
 * browser would find no update and serve the first-ever shell forever. Spelled
 * out rather than a one-line `??` chain because that failure is silent and
 * unrecoverable from the server. !!
 *
 * The version leads so the cache name is legible next to a release; the commit
 * follows because two deploys can share a version and still must invalidate.
 */
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const commit = (process.env.CF_PAGES_COMMIT_SHA || process.env.GITHUB_SHA || "").slice(0, 12);
const stamp = commit ? `${version}+${commit}` : "dev";

const shell = [
  // The pass above made /app the address every link uses, so precaching the path
  // nobody navigates to would leave the app uncached offline. The desktop build
  // skips that pass, where "./app" would instead reject the whole install.
  /* The shell has no marketing page and no router: index.html is not in this
     build, and `cache.addAll()` rejects as a UNIT — one 404 kills the install
     and takes offline support with it, silently. The web keeps both because a
     visitor can land on either. */
  ...(DESKTOP ? ["./app.html"] : ["./", "./index.html", "./app"]),
  "./manifest.webmanifest",
  "./changelog.json", "./CHANGELOG.md",
  ...walk(join(OUT, "src")).filter(f => /\.(js|css)$/.test(f)).map(f => "./" + rel(f)).sort(),
  // icons only: the share card is crawler-facing and has no business in every
  // installed client's offline storage.
  ...walk(join(OUT, "assets/icons")).map(f => "./" + rel(f)).sort(),
];

const swPath = join(OUT, "sw.js");
let sw = readFileSync(swPath, "utf8");

const withShell = sw.replace(/const SHELL = \[[\s\S]*?\n\];/,
  "const SHELL = [\n" + shell.map(p => `  "${p}",`).join("\n") + "\n];");
if (withShell === sw) die("could not rewrite SHELL in sw.js — the declaration format changed");

const withVersion = withShell.replace(/^const VERSION = ".*";/m, `const VERSION = "${stamp}";`);
if (withVersion === withShell) die("could not stamp VERSION in sw.js — the declaration format changed");

/* The offline navigation fallback names the document this build actually has.
   The shell ships app.html and no index.html, so the web's fallback would miss
   the cache and serve the offline page to someone who is merely restarting. */
const withFallback = DESKTOP
  ? withVersion.replace('cache.match("./index.html")', 'cache.match("./app.html")')
  : withVersion;
if (DESKTOP && withFallback === withVersion)
  die("could not repoint the sw offline fallback — sw.js's networkFirst changed");

writeFileSync(swPath, withFallback);

/* ------------------------------------------------------------ report ---- */

/**
 * main.js plus the chunks it imports STATICALLY. Counting the dynamically
 * reachable ones would report exactly the payload the split exists to avoid.
 */
const mainJs = readFileSync(join(OUT, "src/main.js"));
const eagerNames = ["main.js", ...[...mainJs.toString().matchAll(/from\s*"\.\/([\w.-]+\.js)"/g)]
  .map(m => m[1])];
const eager = eagerNames.map(n => readFileSync(join(OUT, "src", n)));
const eagerBytes = br(Buffer.concat(eager));

/* Per SOURCE MODULE, so a failure names a culprit a person can open. Minified
   bytes-in-output rather than compressed: attribution wants a stable per-module
   number, and compressing a module alone answers a question nobody asked —
   shared strings across modules only compress once, so those figures would not
   sum to anything either. The total above is the real, compressed one. */
const eagerSet = new Set(eagerNames);
const perModule = {};
for (const [outPath, out] of Object.entries(appBuild.metafile.outputs)) {
  if (!eagerSet.has(outPath.split("/").pop())) continue;
  for (const [src, info] of Object.entries(out.inputs)) {
    perModule[src] = (perModule[src] ?? 0) + info.bytesInOutput;
  }
}
const ranked = Object.entries(perModule)
  .map(([name, bytes]) => ({ name, bytes }))
  .sort((a, b) => b.bytes - a.bytes);

console.log("\nBuild\n");
console.log(`  service worker  VERSION = ${stamp}`);
console.log(`  app JS, eager   ${(eagerBytes / 1024).toFixed(1)} KB brotli   (${eager.length} files)`);
console.log(`  app CSS         ${(gz(readFileSync(join(OUT, "src/styles/main.css"))) / 1024).toFixed(1)} KB gzip   (1 file, was a 17-deep @import chain)`);
console.log(`  shell entries   ${shell.length}`);
console.log(`  files to publish ${walk(OUT).length}`);

const BASELINE_FILE = join(ROOT, "tools/build/eager-size.json");
const baseline = existsSync(BASELINE_FILE)
  ? JSON.parse(readFileSync(BASELINE_FILE, "utf8"))
  : null;

if (process.argv.includes("--record-size")) {
  writeFileSync(BASELINE_FILE, `${JSON.stringify(
    { bytes: eagerBytes, compression: "brotli", modules: perModule }, null, 2)}\n`);
  console.log(`\n  recorded ${eagerBytes} B brotli as the new baseline\n`);
} else if (eagerBytes > EAGER_JS_CEILING) {
  blame(baseline);
  die(`eager JS is ${(eagerBytes / 1024).toFixed(1)} KB brotli, over the hard `
    + `${(EAGER_JS_CEILING / 1024).toFixed(0)} KB ceiling in tools/build/build.mjs. `
    + `This one is not a ratchet — get back under it, or change the ceiling on purpose.`);
} else if (baseline && eagerBytes > baseline.bytes * (1 + BASELINE_TOLERANCE)) {
  blame(baseline);
  die(`eager JS grew ${eagerBytes - baseline.bytes} B over the recorded `
    + `${baseline.bytes} B baseline. If that is intended, run `
    + `\`npm run build -- --record-size\` and commit tools/build/eager-size.json `
    + `so the growth is in the diff.`);
} else {
  const left = EAGER_JS_CEILING - eagerBytes;
  console.log(`\n  within budget (${(left / 1024).toFixed(1)} KB under the ceiling`
    + `${baseline ? `, ${eagerBytes - baseline.bytes >= 0 ? "+" : ""}${eagerBytes - baseline.bytes} B vs baseline` : ""})\n`);
}

/** Name the movers. Without this a budget failure is a number and a shrug. */
function blame(base) {
  const was = base?.modules ?? {};
  const moved = [...new Set([...Object.keys(perModule), ...Object.keys(was)])]
    .map(name => ({ name, delta: (perModule[name] ?? 0) - (was[name] ?? 0) }))
    .filter(m => m.delta !== 0)
    .sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta))
    .slice(0, 8);

  if (moved.length) {
    console.log("\n  moved since the baseline (minified bytes in the eager output):");
    for (const m of moved) {
      console.log(`    ${((m.delta > 0 ? "+" : "") + m.delta).padStart(8)} B  ${m.name}`);
    }
  } else {
    console.log("\n  biggest eager modules (minified bytes in the eager output):");
    for (const m of ranked.slice(0, 8)) console.log(`    ${String(m.bytes).padStart(8)} B  ${m.name}`);
  }
  console.log("");
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function die(msg) {
  console.error(`\n::error::${msg}`);
  process.exit(1);
}
